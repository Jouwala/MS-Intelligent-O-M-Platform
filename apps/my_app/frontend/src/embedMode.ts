/* ============================================================================
 * 嵌入（embed）模式判定 —— 全站单一口径
 * ----------------------------------------------------------------------------
 * URL 带 `?embed=1`（或 `?embed=true` / `?layout=bare`）时只渲染页面本体，
 * 隐藏侧栏 / Header，供统一门户 iframe 或大屏单模块嵌入使用。
 *
 * ⚠️ 刻意**不用**「有无 ?page= 参数」判断：?page= 是应用内导航的常态参数，
 *    拿它当开关会让侧栏在进入某一页的下一秒消失且再也点不回来
 *    （2026-10-18 踩过，原因见 App.tsx 里 readBareModule 的注释）。
 *
 * 2026-11-16 从 App.tsx 抽成独立模块：ipt_power 的地图行需要知道「这是不是
 * 嵌入场景」来决定最小高度（嵌入时视口就是 iframe，口径说明展开应当压缩地图；
 * 直开应用外壳时页面可以滚动，不能把地图压成一条）。此前只有 App.tsx 一份
 * 判定，页内再写一份就会漂移 —— 例如门户将来换开关名，App 跟着改、页内忘改。
 * ========================================================================== */
export function isEmbedMode(): boolean {
  try {
    const sp = new URLSearchParams(window.location.search)
    return sp.get('embed') === '1' || sp.get('embed') === 'true' || sp.get('layout') === 'bare'
  } catch { return false }
}
